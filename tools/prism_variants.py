"""Make Prism itself produce controlled-variation documents.

Each variant is: open a copy of the seed -> GoTo the graph -> run a few Prism
script commands (SetAxisLimits, SetAxisTitle, SetGraphTitle, ApplyColorScheme,
...) -> ExportPDF -> Save -> Close. Saved variants differ from a "control"
(the same open/save with no commands) only by what the commands changed, so a
structural PCFF diff (tools/pcff_diff.py) shows the bytes behind each setting.

Usage (variants are defined in a small Python file that exposes VARIANTS =
{name: [script lines]}):
  .venv/bin/python -I tools/prism_variants.py <seed.prism> <variants.py> <out_dir> [--graph 1]
"""

from __future__ import annotations

import argparse
import json
import os
import runpy
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from prism_auto import _run_script, marker, read_log  # noqa: E402


def build(d: str, graph: int, commands: list[str]) -> str:
    lines = ["// generated by tools/prism_variants.py", f'SetPath "{d}"']
    lines += marker("00_start") + ["Open input.prism"] + marker("01_open")
    lines += [f"GoTo G {graph}"] + marker("02_goto")
    for i, c in enumerate(commands):
        lines += [c] + marker(f"03_cmd{i:02d}")
    lines += [f"GoTo G {graph}", "ExportPDF graph.pdf"] + marker("04_pdf")  # commands may move the cursor
    lines += ["Save variant.prism"] + marker("05_saved")
    lines += ["Close"] + marker("99_closed") + ["CloseScriptDialog"]
    return "\r\n".join(lines) + "\r\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("seed")
    ap.add_argument("variants")
    ap.add_argument("out")
    ap.add_argument("--graph", type=int, default=1)
    ap.add_argument("--timeout", type=float, default=8)
    a = ap.parse_args()
    variants: dict[str, list[str]] = {"control": []} | runpy.run_path(a.variants)["VARIANTS"]
    out = os.path.abspath(a.out)
    if " " in out:
        raise SystemExit("output path must not contain spaces")
    os.makedirs(out, exist_ok=True)
    report = {}
    for name, cmds in variants.items():
        d = os.path.join(out, name)
        if os.path.exists(d):
            shutil.rmtree(d)
        os.makedirs(d)
        shutil.copy2(a.seed, os.path.join(d, "input.prism"))
        events: list[str] = []
        status = _run_script(d, "job.pzc", build(d, a.graph, cmds), "m_99_closed.txt", a.timeout, events)
        ok = os.path.exists(os.path.join(d, "variant.prism"))
        log = read_log(os.path.join(d, "job.log")).strip()
        report[name] = {"commands": cmds, "status": status, "saved": ok, "events": events, "log_tail": log[-300:]}
        print(f"  {'OK ' if status == 'ok' and ok else 'ERR'} {name:28s} {cmds}" + ("" if status == "ok" else f"  ({events[-1][:160] if events else status})"), flush=True)
    with open(os.path.join(out, "report.json"), "w") as fh:
        json.dump(report, fh, indent=2, ensure_ascii=False)


if __name__ == "__main__":
    main()
