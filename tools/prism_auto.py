"""Drive the local Prism app with its own scripting language (.pzc), with no
clicking.

For every input .prism it:
  * copies the file into <out>/<stem>/input.prism (the original is never touched)
  * exports every graph  -> graph_<i>.pdf / graph_<i>.png
  * exports every layout -> layout_<i>.pdf / layout_<i>.png
  * exports every table  -> data_<j>.csv
  * exports every result -> result_<k>.csv
  * saves Prism's own re-save -> resaved.prism
  * writes a marker after every step, so a hang shows exactly where it stopped

Usage:
  .venv/bin/python -I tools/prism_auto.py <out_dir> <file.prism> [...]
      [--timeout 60] [--no-png] [--no-resave]

Prism opens a .pzc via `open -a "Prism 11" script.pzc` and runs it. If no
new marker appears for --timeout seconds, the run is treated as stuck on a
modal dialog: the tool tries to read the dialog text through System Events
(needs Accessibility permission, which is asked for once), records it, and
presses the default button so the batch can continue.

Uses only Prism's documented script commands (FAQ 1648 / ScriptHelper).
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from refract.formats.zipio import ZipArchive

APP = "Prism 11"


def inspect(path: str) -> dict:
    """Count sheets the script will visit, in navigator order."""
    from refract.formats import open_document, sniff
    with open(path, "rb") as fh:
        kind = sniff(fh.read(64))
    if kind != "prism":  # XML: graphs live in <Template>; legacy binary: tables unreadable for us
        return {"graphs": 0, "data": len(open_document(path).tables), "results": 0, "layouts": 0}
    z = ZipArchive.open(path)
    doc = json.loads(z.read("document.json"))
    sheets = doc.get("sheets", {})
    n_results = 0
    for a in sheets.get("analyses", []):
        try:
            n_results += 1 if json.loads(z.read(f"analyses/{a}/sheet.json")) else 0
        except KeyError:
            pass
    return {"graphs": len(sheets.get("graphs", [])), "data": len(sheets.get("data", [])),
            "results": n_results, "layouts": len(sheets.get("layouts", []))}


def marker(n: str) -> list[str]:
    return [f"OpenOutput m_{n}.txt Clear", f'WText "{n}"', "CloseOutput"]


def build_resave_script(d: str, source: str = "input.prism", n_results: int = 0, n_graphs: int = 0,
                        before_save: list[str] | None = None) -> str:
    """Open, show every results sheet (Prism computes analyses lazily, only
    when a result is displayed) and every graph (Prism refreshes a graph's
    PCFF caches - axis ranges, data extents - only when it is displayed;
    verified, docs/experiments.md phase 3), then save."""
    lines = ["// generated by tools/prism_auto.py (phase 1: open, visit results and graphs, re-save, close)",
             f'SetPath "{d}"']
    lines += marker("A0_start") + [f"Open {source}"] + marker("A1_open")
    if before_save:  # script commands run on the opened file (e.g. GoTo D 4, DuplicateFamily "Copy of ")
        lines += before_save + marker("A1_before")
    for i in range(1, n_results + 1):
        lines += [f"GoTo R {i}"] + marker(f"A1r{i:03d}")
    for i in range(1, n_graphs + 1):
        lines += [f"GoTo G {i}"] + marker(f"A1g{i:03d}")
    lines += ["Save resaved.prism"] + marker("A2_saved")
    lines += ["Close"] + marker("A9_closed") + ["CloseScriptDialog"]
    return "\r\n".join(lines) + "\r\n"


def build_script(job: dict, png: bool, resave: bool, source: str = "input.prism") -> str:
    d, c = job["dir"], job["counts"]
    lines = ["// generated by tools/prism_auto.py (phase 2: export)", f'SetPath "{d}"']
    lines += marker("00_start")
    lines.append(f"Open {source}")
    lines += marker("01_open")
    if job.get("visit_first"):  # show every graph once before exporting (see --visit-first)
        for i in range(1, c["graphs"] + 1):
            lines += [f"GoTo G {i}"] + marker(f"01v{i:03d}")
    step = 2
    for i in range(1, c["graphs"] + 1):
        lines += [f"GoTo G {i}", f"ExportPDF graph_{i}.pdf"]
        if png:
            lines.append(f"ExportPNG graph_{i}.png")
        lines += marker(f"{step:02d}_graph{i}")
        step += 1
    for i in range(1, c.get("layouts", 0) + 1):  # layouts export like graphs (GoTo L)
        lines += [f"GoTo L {i}", f"ExportPDF layout_{i}.pdf"]
        if png:
            lines.append(f"ExportPNG layout_{i}.png")
        lines += marker(f"{step:02d}_layout{i}")
        step += 1
    for i in range(1, c["data"] + 1):
        lines += [f"GoTo D {i}", f"ExportTable data_{i}.csv"]
        lines += marker(f"{step:02d}_data{i}")
        step += 1
    for i in range(1, (0 if c.get("results_visit_only") else c["results"]) + 1):
        lines += [f"GoTo R {i}", f"ExportTable result_{i}.csv"]
        lines += marker(f"{step:02d}_result{i}")
        step += 1
    lines.append("Close")
    lines += marker("99_closed")
    lines.append("CloseScriptDialog")
    return "\r\n".join(lines) + "\r\n"


def markers(d: str) -> list[str]:
    return sorted(f for f in os.listdir(d) if f.startswith("m_")) if os.path.isdir(d) else []


def _osa(script: str, timeout: float = 20) -> tuple[int, str]:
    try:
        r = subprocess.run(["osascript", "-e", script], capture_output=True, text=True, timeout=timeout)
        return r.returncode, (r.stdout if r.returncode == 0 else r.stderr).strip()
    except subprocess.TimeoutExpired:
        return 1, "<osascript timed out>"


def prism_running() -> bool:
    return subprocess.run(["pgrep", "-x", "Prism"], capture_output=True).returncode == 0


def window_texts() -> str:
    """Static texts of Prism's windows (needs Accessibility)."""
    code, names = _osa('tell application "System Events" to tell process "Prism" to get name of every window')
    code2, texts = _osa('tell application "System Events" to tell process "Prism" to get value of static texts of every window')
    code3, sheets = _osa('tell application "System Events" to tell process "Prism" to get value of static texts of sheets of every window')
    return f"windows=[{names}] texts=[{texts}] sheets=[{sheets if code3 == 0 else ''}]"


def press_return() -> None:
    _osa('tell application "System Events" to tell process "Prism" to set frontmost to true')
    _osa('tell application "System Events" to keystroke return')


def recover() -> None:
    """Close the script dialog, quit Prism (Don\'t Save), force-kill as a last resort."""
    _osa('tell application "System Events" to tell process "Prism" to click button "Close" of window "GraphPad Prism Script"')
    _osa('tell application "Prism 11" to quit', timeout=10)
    for _ in range(10):
        if not prism_running():
            return
        _osa('tell application "System Events" to tell process "Prism" to keystroke "d" using command down')
        time.sleep(1)
    subprocess.run(["pkill", "-x", "Prism"])
    time.sleep(2)


def read_log(path: str) -> str:
    if not os.path.exists(path):
        return ""
    raw = open(path, "rb").read()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return raw.decode("utf-16")
    if raw[:1] == b"\x00":
        return raw.decode("utf-16-be", "replace")
    if raw[1:2] == b"\x00":
        return raw.decode("utf-16-le", "replace")
    return raw.decode("utf-8", "replace")


def _run_script(d: str, name: str, text: str, done_marker: str, timeout: float, events: list[str]) -> str:
    script = os.path.join(d, name)
    with open(script, "w", encoding="utf-8") as fh:
        fh.write(text)
    subprocess.run(["open", "-a", APP, script], check=True)
    last, last_t, nudges = None, time.time(), 0
    while True:
        time.sleep(0.3)
        m = markers(d)
        if m != last:
            last, last_t = m, time.time()
        if done_marker in m:
            time.sleep(0.7)  # let CloseScriptDialog finish
            return "ok"
        if time.time() - last_t > timeout:
            texts = window_texts()
            events.append(f"{name}: stalled after {m[-1] if m else 'start'}: {texts}")
            if "ERROR" in texts or nudges >= 2:
                recover()
                return "script_error" if "ERROR" in texts else "stuck"
            press_return()  # dismiss an alert (e.g. "file damaged") and keep going
            events.append(f"{name}: pressed Return")
            nudges += 1
            last_t = time.time()


def run_job(job: dict, png: bool, resave: bool, timeout: float) -> dict:
    d = job["dir"]
    t0 = time.time()
    events: list[str] = []
    status, source = "ok", job.get("input", "input.prism")
    if resave:
        status = _run_script(d, "resave.pzc", build_resave_script(d, source, job["counts"].get("results", 0),
                                                                   job["counts"].get("graphs", 0),
                                                                   job.get("before_save")),
                             "m_A9_closed.txt", timeout, events)
        if os.path.exists(os.path.join(d, "resaved.prism")):
            source = "resaved.prism"
            job["counts_after_prism"] = inspect(os.path.join(d, source))
    if status == "ok":
        counts = job.get("counts_after_prism", job["counts"])
        status = _run_script(d, "export.pzc", build_script({**job, "counts": counts}, png, resave, source),
                             "m_99_closed.txt", timeout, events)
    return {"stem": job["stem"], "status": status, "seconds": round(time.time() - t0, 1),
            "counts_ours": job["counts"], "counts_after_prism": job.get("counts_after_prism"),
            "markers": markers(d), "events": events,
            "prism_log": "\n".join(read_log(os.path.join(d, n)).strip()[-400:] for n in ("resave.log", "export.log")),
            "produced": sorted(f for f in os.listdir(d)
                               if not f.startswith("m_") and not f.endswith((".pzc", ".log")) and not f.startswith("input."))}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("files", nargs="+")
    ap.add_argument("--timeout", type=float, default=10)
    ap.add_argument("--no-png", action="store_true")
    ap.add_argument("--no-resave", action="store_true")
    ap.add_argument("--tables-only", action="store_true", help="export data tables only")
    ap.add_argument("--before-save", default="", help="script commands run after opening, ';'-separated")
    ap.add_argument("--visit-first", action="store_true",
                    help="show every graph once before exporting (a pie exported first can come out blank)")
    a = ap.parse_args()

    out = os.path.abspath(a.out)
    if " " in out:
        raise SystemExit("output path must not contain spaces (Prism script paths are unquoted)")
    os.makedirs(out, exist_ok=True)
    jobs = []
    used: set[str] = set()
    for f in a.files:
        stem = os.path.splitext(os.path.basename(f))[0].replace(" ", "_")
        base, k = stem, 2
        while stem in used:  # same file name in different folders
            stem, k = f"{base}_{k}", k + 1
        used.add(stem)
        d = os.path.join(out, stem)
        if os.path.exists(d):
            shutil.rmtree(d)
        os.makedirs(d)
        ext = os.path.splitext(f)[1].lower() or ".prism"
        shutil.copy2(f, os.path.join(d, "input" + ext))
        counts = inspect(f)
        if a.tables_only:
            counts = {**counts, "graphs": 0, "results_visit_only": True}
        jobs.append({"file": os.path.abspath(f), "stem": stem, "dir": d, "counts": counts, "input": "input" + ext,
                     "before_save": [c.strip() for c in a.before_save.split(";") if c.strip()],
                     "visit_first": a.visit_first})

    results = []
    t0 = time.time()
    for j in jobs:
        r = run_job(j, png=not a.no_png, resave=not a.no_resave, timeout=a.timeout)
        results.append(r)
        flag = {"ok": "OK ", "script_error": "ERR", "stuck": "!! "}[r["status"]]
        lost = "" if not r["counts_after_prism"] or r["counts_after_prism"] == r["counts_ours"] else f"  sheets ours {r['counts_ours']} -> Prism {r['counts_after_prism']}"
        print(f"  {flag} {r['stem']:34s} {r['seconds']:5.1f}s {len(r['produced'])} outputs{lost}"
              + (f"  last step: {r['markers'][-1] if r['markers'] else '-'}" if r["status"] != "ok" else ""), flush=True)
        for e in r["events"]:
            print(f"        {e[:300]}")
    with open(os.path.join(out, "summary.json"), "w") as fh:
        json.dump({"elapsed_s": round(time.time() - t0, 1), "files": results}, fh, indent=2, ensure_ascii=False)
    print(f"done: {sum(r['status'] == 'ok' for r in results)}/{len(results)} ok in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
