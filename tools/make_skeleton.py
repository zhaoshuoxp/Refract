"""Write refract/formats/pcff/skeleton_data.py: per graph kind, the chunks
of a graph that Prism does not rebuild on open (E-levelc), taken from the
shipped seed graphs (Prism's default graphs of neutral generated tables,
refract/formats/seed_graphs; tools/make_seeds.py).

Each skeleton keeps its six data-set plots (header, record, data-set link),
the plot list 0x0015 and the property store, so a graph can be written with
plot formatting; refract.formats.pcff.skeleton drops what a graph does not
need. Run after the seeds change:
  .venv/bin/python tools/make_skeleton.py
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)

from refract.formats import seeds
from refract.formats.pcff import skeleton as S
from refract.formats.pcff.walker import parse

OUT = os.path.join(ROOT, "refract", "formats", "pcff", "skeleton_data.py")


def main() -> int:
    lib = seeds.library()
    lines = ['"""Generated by tools/make_skeleton.py from the shipped seed graphs; do not edit.',
             "",
             "SKELETONS: per kind, (tag, payload) in stream order; payload None = close",
             "marker (refract.formats.pcff.skeleton). ROLES: per kind, the fenIDs it uses",
             'for the table\'s row titles and X column."""',
             "",
             "ROLES = {" + ", ".join(f"{k!r}: ({lib[k].row_fen!r}, {lib[k].x_fen!r})" for k in S.KINDS if k in lib)
             + "}  # (row-titles, X) data-set fenIDs the skeleton names",
             "",
             "SKELETONS = {"]
    for kind in S.KINDS:
        if kind not in lib:
            continue
        drop = frozenset() if kind in S.KEEP_OBJECTS else S.BUILT_OBJECTS - {S.PLOT}
        ch = S.reduce(parse(lib[kind].blob), S.PLOT_KEPT | S.EXTRA_KEPT.get(kind, frozenset()), drop_types=drop)
        lines.append(f"    {kind!r}: [")
        for c in ch:
            lines.append(f"        ({c.tag:#06x}, None)," if c.is_marker else
                         f"        ({c.tag:#06x}, bytes.fromhex({c.payload.hex()!r})),")
        lines.append("    ],")
        print(kind, len(ch), "chunks")
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
