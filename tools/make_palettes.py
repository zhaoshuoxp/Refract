"""Generate refract/render/palette_library.py from the palette sources of
two R packages:

  * RColorBrewer (R/ColorBrewer.R; the ColorBrewer colours by Cynthia A.
    Brewer, Apache License 2.0): each palette at its largest size.
  * ggsci (R/palettes.R; GPL >= 3): its discrete and continuous palettes.

  curl -sSLO https://raw.githubusercontent.com/cran/RColorBrewer/master/R/ColorBrewer.R
  curl -sSLO https://raw.githubusercontent.com/nanxstats/ggsci/master/R/palettes.R
  .venv/bin/python -I tools/make_palettes.py ColorBrewer.R palettes.R > refract/render/palette_library.py
"""

from __future__ import annotations

import re
import sys

BREWER_KINDS = {
    "Qualitative": ["Accent", "Dark2", "Paired", "Pastel1", "Pastel2", "Set1", "Set2", "Set3"],
    "Sequential": ["Blues", "BuGn", "BuPu", "GnBu", "Greens", "Greys", "Oranges", "OrRd", "PuBu", "PuBuGn", "PuRd",
                   "Purples", "RdPu", "Reds", "YlGn", "YlGnBu", "YlOrBr", "YlOrRd"],
    "Diverging": ["BrBG", "PiYG", "PRGn", "PuOr", "RdBu", "RdGy", "RdYlBu", "RdYlGn", "Spectral"],
}
# ggsci palettes by menu group (package name -> group); the rest go to "Other"
GGSCI_GROUPS = {
    "Journals": ["npg", "aaas", "nejm", "lancet", "jama", "bmj", "jco", "frontiers"],
    "Science tools": ["ucscgb", "d3", "igv", "locuszoom", "cosmic", "gephi", "observable", "primer", "atlassian"],
    "Universities and UI": ["uchicago", "flatui"],
    "TV and film": ["simpsons", "futurama", "rickandmorty", "startrek", "tron"],
}
HEX = re.compile(r'"(#[0-9A-Fa-f]{6})"')


def brewer(src: str) -> dict[str, dict[str, list[str]]]:
    out: dict[str, dict[str, list[str]]] = {}
    blocks = re.split(r"\n\s*(\w+)\s*=\s*switch\(n-2,", src)
    found = {blocks[i]: blocks[i + 1] for i in range(1, len(blocks) - 1, 2)}
    for kind, names in BREWER_KINDS.items():
        out[kind] = {}
        for name in names:
            rgbs = re.findall(r"rgb\(c\(([\d,\s]+)\),\s*c\(([\d,\s]+)\),\s*c\(([\d,\s]+)\)", found[name])
            r, g, b = ([int(x) for x in part.split(",")] for part in rgbs[-1])  # the largest size
            out[kind][name] = [f"#{a:02X}{c:02X}{d:02X}" for a, c, d in zip(r, g, b, strict=True)]
    return out


def ggsci(src: str) -> dict[str, dict[str, list[str]]]:
    discrete, continuous = src.split("# Continuous Color Palettes", 1)
    out: dict[str, dict[str, list[str]]] = {g: {} for g in [*GGSCI_GROUPS, "Other", "Continuous"]}

    def entries(text: str):
        # ggsci_db$"pkg"$"variant" <- c(...)   or   ggsci_db$"pkg" <- list("variant" = c(...), ...)
        for m in re.finditer(r'ggsci_db\$"(\w+)"\$"(\w+)"\s*<-\s*c\((.*?)\n\)', text, re.DOTALL):
            yield m.group(1), m.group(2), HEX.findall(m.group(3))
        for m in re.finditer(r'ggsci_db\$"(\w+)"\s*<-\s*list\((.*?)\n\)\n', text, re.DOTALL):
            for v in re.finditer(r'"?(\w+)"?\s*=\s*c\((.*?)\)', m.group(2), re.DOTALL):
                yield m.group(1), v.group(1), HEX.findall(v.group(2))

    for pkg, variant, colors in entries(discrete):
        group = next((g for g, pkgs in GGSCI_GROUPS.items() if pkg in pkgs), "Other")
        if colors:
            out[group][f"{pkg} {variant}" if variant != "default" else pkg] = [c.upper() for c in colors]
    for pkg, variant, colors in entries(continuous):
        if colors:
            out["Continuous"][f"{pkg} {variant}" if variant != "default" else pkg] = [c.upper() for c in colors]
    return {g: v for g, v in out.items() if v}


def main() -> None:
    with open(sys.argv[1], encoding="utf-8") as f1, open(sys.argv[2], encoding="utf-8") as f2:
        b, g = brewer(f1.read()), ggsci(f2.read())
    print('"""Colour palettes of two R packages, for Graph ▸ Color Scheme (generated by')
    print("tools/make_palettes.py; do not edit).")
    print()
    print("RColorBrewer: the ColorBrewer palettes by Cynthia A. Brewer (colorbrewer2.org),")
    print("Apache License 2.0; each at its largest size. ggsci (Nan Xiao and contributors),")
    print('GPL (>= 3). Their notices are in the application\'s LICENSES folder."""')
    print()
    for name, data in (("BREWER", b), ("GGSCI", g)):
        print(f"{name}: dict[str, dict[str, list[str]]] = {{")
        for group, pals in data.items():
            print(f"    {group!r}: {{")
            for pal, cols in pals.items():
                print(f"        {pal!r}: {cols!r},")
            print("    },")
        print("}")
    print()


if __name__ == "__main__":
    main()
